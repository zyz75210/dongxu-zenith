import { Easing } from 'react-native';

/**
 * 全局转场参数 —— 所有页面切换共用这一套节奏，改这里一处、全 App 同步。
 *
 * ## 当前形态：中性薄雾（不闪）
 * 一次转场 = 整屏轻轻压一层冷灰，到最浓时页面正好换完，再散开。
 * 只动一个纯色视图的透明度，没有任何离屏渲染，所以不可能出现逐帧闪动。
 *
 * ## 为什么关掉了原生模糊
 * 原生模糊每次转场都要重新抓一张整屏位图（异步、走独立线程），
 * 抓取完成的时刻和当前帧对不上，动画那几帧里会交替显示新旧两张快照 ——
 * 视觉上就是闪，而且整屏一糊一清本身就是一次亮度突变，看久了眼睛很累。
 * 这个闪不是调参能解决的，只能换实现。
 * 打完正式包（非 Expo Go debug）想再试，把 `useBlur` 改成 true 即可，其余参数都已备好。
 */
export const MOTION = {
  /**
   * 是否使用原生模糊。true = 真模糊（可能闪、吃性能）；false = 中性薄雾（稳、零成本）
   * Expo Go 里建议保持 false。
   */
  useBlur: false,

  /** 起雾时长（二级页面）：升到最浓 */
  fog: 110,
  /** 对焦时长（二级页面）：雾散掉、画面变清晰 */
  enter: 200,

  /** 切 tab 的起雾 / 对焦：高频操作，整体再短一档 */
  tabFog: 90,
  tab: 170,

  /** 二级页面自身的淡入 / 淡出：只负责"接住"换页那一帧的硬切 */
  paneIn: 100,
  /** 退场淡出：雾还在，页面已经让开了，不会出现两层内容叠着 */
  exit: 120,

  /** tab 页面的淡出（旧页只是让位，不做视觉变化） */
  paneOut: 130,

  /**
   * 薄雾峰值浓度（0-1，只在不使用原生模糊时生效）。
   * 0.07 = 一层几乎看不出来的灰，只够让换页那一帧不"跳"。
   * 这个值越大越容易"扎眼"（整屏亮度被压下去），想更明显最多到 0.12。
   * 再想明显又不扎眼，方向不是加浓度，而是把 `fog`/`enter` 放长。
   */
  wash: 0.07,

  // ——— 以下只在使用原生模糊（useBlur = true）时生效 ———

  /**
   * 雾最浓时的不透明度（0-1）。满 1 = 整屏糊成一片白，是最扎眼的一步，
   * 所以哪怕开了模糊也只到 0.68。
   */
  peak: 0.68,
  /** 模糊强度（1-100）。安卓实际强度 = intensity / blurReductionFactor */
  blur: 44,
  /** 安卓强度衰减系数，与库默认值一致：不动它，只靠 intensity 调节观感 */
  blurReductionFactor: 4,

  /**
   * 起雾 / 对焦必须是**同一条曲线的前后半段**，否则不丝滑。
   *
   * 之前是「上升 inOut + 下降 out」：上升到顶时速度已经降到 0，下降一开始速度就是最大，
   * 顶点处速度突变 —— 眼睛看到的就是"一下顿住再散开"。
   * 现在两段都用 inOut(sin)：起点、顶点、终点速度都是 0，
   * 整个转场就是一次连续的"吸气—呼气"，中间没有任何一个拐点。
   */
  easeFog: Easing.inOut(Easing.sin),
  easeFocus: Easing.inOut(Easing.sin),
  /** 页面淡入 / 淡出：同样两头缓，避免出现"啪"地显影 */
  easeFade: Easing.inOut(Easing.quad),
} as const;
